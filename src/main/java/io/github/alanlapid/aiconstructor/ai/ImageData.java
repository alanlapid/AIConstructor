package io.github.alanlapid.aiconstructor.ai;

import java.util.Base64;

/** A downloaded reference photo. */
public record ImageData(byte[] data, String mimeType) {

    public String base64() {
        return Base64.getEncoder().encodeToString(data);
    }

    /** Detects PNG, JPEG or WEBP from the file header; returns null for anything else. */
    public static String sniffMime(byte[] d) {
        if (d.length >= 8 && (d[0] & 0xFF) == 0x89 && d[1] == 'P' && d[2] == 'N' && d[3] == 'G') {
            return "image/png";
        }
        if (d.length >= 3 && (d[0] & 0xFF) == 0xFF && (d[1] & 0xFF) == 0xD8 && (d[2] & 0xFF) == 0xFF) {
            return "image/jpeg";
        }
        if (d.length >= 12 && d[0] == 'R' && d[1] == 'I' && d[2] == 'F' && d[3] == 'F'
                && d[8] == 'W' && d[9] == 'E' && d[10] == 'B' && d[11] == 'P') {
            return "image/webp";
        }
        return null;
    }
}
